function sliderKnobX(b) { return lerp(480, 960, sliderP(b)) + 2; }
function cursorAt(b) {
  if (b >= 20.6 && b <= 23.4) return [sliderKnobX(b), 1272, 1, 1];
  for (let i = 0; i < CUR.length - 1; i++) {
    const a = CUR[i], c = CUR[i + 1];
    if (b >= a[0] && b < c[0]) {
      const u = c[0] - a[0] < .001 ? 1 : eIO((b - a[0]) / (c[0] - a[0]));
      if (a[0] === 15.99 && c[0] === 16) return [a[1], a[2], 0, 1];
      return [lerp(a[1], c[1], u), lerp(a[2], c[2], u), lerp(a[3], c[3], (b - a[0]) / (c[0] - a[0])), c[4] === 0 && a[4] === 1 ? 1 - prog(b, a[0], c[0]) : a[4] === 0 && c[4] === 1 ? prog(b, a[0], c[0]) : a[4]];
    }
  }
  return [0, 0, 0, 0];
}
function renderCursor(b) {
  const [x, y, press, shown] = cursorAt(b); const c = $('cursor');
  c.style.display = shown > .01 ? 'block' : 'none';
  c.style.transform = `translate(${x - 6}px,${y - 4}px) scale(${(.9 + .1 * shown) * (1 - .14 * press)})`;
}
function dragRect(b) {
  if (b < 35.0 || b >= 38.75) return { on: false };
  const [cx, cy] = cursorAt(b), lift = spring(b, 35.05, 2.4, .7);
  const thumb = [cx + 80 - 115, cy + 70 - 115, 230, 230, 28];
  let r = lerpA([PH.x, PH.y, PH.w, PH.h, PH.r], thumb, lift);
  if (b >= 37.6) r = lerpA(thumb, [MACW.x + 40, MACW.y + VP.y + 76, 720, 300, 22], spring(b, 37.6, 2.2, .7));
  return { on: true, r };
}
